export type Key = keyof typeof en;

function lang(): string {
  try {
    return (window.localStorage.getItem("language") || navigator.language || "en").toLowerCase();
  } catch {
    return "en";
  }
}

export const isRu = () => lang().startsWith("ru");
export const locale = () => (isRu() ? "ru-RU" : lang().startsWith("en") ? "en-US" : navigator.language || "en-US");

export function t<K extends Key>(key: K): (typeof en)[K] {
  return (isRu() ? ru : en)[key];
}
